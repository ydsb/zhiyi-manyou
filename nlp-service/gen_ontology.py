def merged() -> dict:
    """合并主数据与补充数据（同名二级学科的内容合并，不覆盖）。"""
    out: dict[str, dict[str, list]] = {}
    for source in (SKILLS, SUPPLEMENT, SUPPLEMENT2):
        for l1, majors in source.items():
            for l2, items in majors.items():
                out.setdefault(l1, {}).setdefault(l2, [])
                out[l1][l2].extend(items)
    # 去重：同名技能只保留首次出现（主数据优先）
    seen: set[str] = set()
    for l1, majors in out.items():
        for l2 in list(majors.keys()):
            kept = []
            for row in majors[l2]:
                name = row[0]
                if name in seen:
                    continue
                seen.add(name)
                kept.append(row)
            majors[l2] = kept
    return out


def iter_skills():
    """展开为 (门类, 二级学科, 名称, 别名, 难度, 描述) 序列。"""
    for l1, majors in merged().items():
        for l2, items in majors.items():
            for name, alias, difficulty, desc in items:
                yield l1, l2, name, alias, difficulty, desc


def stats() -> dict:
    """统计门类数、二级学科数、技能总数。"""
    l1s = set()
    l2s = set()
    n = 0
    per_l1: dict[str, int] = {}
    for l1, l2, *_ in iter_skills():
        l1s.add(l1)
        l2s.add((l1, l2))
        n += 1
        per_l1[l1] = per_l1.get(l1, 0) + 1
    return {"disciplines": len(l1s), "majors": len(l2s), "skills": n, "perL1": per_l1}


def gen_sql() -> str:
    """生成可导入的 SQL。

    用 ON DUPLICATE KEY UPDATE 保证幂等：重复导入只更新可维护字段，
    不会因主键冲突失败，也不会把已有关联数据弄丢。
    由于 zy_skill 没有 name 唯一索引，这里用 NOT EXISTS 判断更稳妥。
    """
    lines = [
        "-- =============================================================================",
        "--  知驿·漫游 —— 技能本体种子数据（由 gen_ontology.py 生成，请勿手工修改）",
        "--",
        "--  规模：见文件末尾统计。覆盖 13 个学科门类、多个二级学科。",
        "--  别名（alias）是 FR-M2-07「同义词库 / 跨域术语映射」的载体，",
        "--  登记原则：只要某个说法是学生真实会用的表达、且不是标签名的子串，就登记。",
        "--",
        "--  幂等：同名技能已存在时只更新别名/描述/难度/门类，不重复插入。",
        "-- =============================================================================",
        "",
        "USE `zhiyi_manyou`;",
        "",
    ]
    for l1, l2, name, alias, difficulty, desc in iter_skills():
        esc = lambda s: str(s).replace("\\", "\\\\").replace("'", "''")  # noqa: E731
        lines.append(
            "INSERT INTO `zy_skill` (`name`, `alias`, `category_l1`, `category_l2`, "
            "`difficulty`, `description`, `hot_score`, `status`)\n"
            f"SELECT '{esc(name)}', '{esc(alias)}', '{esc(l1)}', '{esc(l2)}', "
            f"{difficulty}, '{esc(desc)}', 0, 1\n"
            "FROM DUAL WHERE NOT EXISTS "
            f"(SELECT 1 FROM `zy_skill` WHERE `name` = '{esc(name)}');"
        )
        # 已存在则更新可维护字段（别名是重点：语义匹配依赖它）
        lines.append(
            "UPDATE `zy_skill` SET "
            f"`alias` = '{esc(alias)}', `category_l1` = '{esc(l1)}', "
            f"`category_l2` = '{esc(l2)}', `difficulty` = {difficulty}, "
            f"`description` = '{esc(desc)}' "
            f"WHERE `name` = '{esc(name)}' AND `status` = 1;"
        )
    s = stats()
    lines += [
        "",
        "-- -----------------------------------------------------------------------------",
        f"-- 统计：技能 {s['skills']} 条 / 二级学科 {s['majors']} 个 / 门类 {s['disciplines']} 个",
        "-- -----------------------------------------------------------------------------",
        "SELECT COUNT(*) AS 技能总数, COUNT(DISTINCT category_l2) AS 二级学科数,",
        "       COUNT(DISTINCT category_l1) AS 门类数 FROM `zy_skill` WHERE `status` = 1;",
    ]
    return "\n".join(lines) + "\n"


def gen_import_text() -> str:
    """生成后台导入接口所需的文本（名称,门类,二级学科,难度,别名,描述）。"""
    lines = [
        "# 知驿·漫游 技能本体导入文本",
        "# 格式：名称,门类,二级学科,难度,别名(用|分隔),描述",
        "# 由 gen_ontology.py 生成",
    ]
    for l1, l2, name, alias, difficulty, desc in iter_skills():
        # 字段内的逗号必须换成全角，否则会破坏列结构
        clean = lambda s: str(s).replace(",", "，")  # noqa: E731
        lines.append(f"{clean(name)},{clean(l1)},{clean(l2)},{difficulty},{clean(alias)},{clean(desc)}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="生成技能本体数据")
    parser.add_argument("--out", default=None, help="输出 SQL 文件路径")
    parser.add_argument("--import-text", default=None, help="输出后台导入文本路径")
    parser.add_argument("--stats", action="store_true", help="只打印统计")
    args = parser.parse_args()

    s = stats()
    print("=" * 66)
    print("技能本体统计")
    print("=" * 66)
    print(f"  学科门类   {s['disciplines']} 个（需求要求覆盖多学科，无硬性下限）")
    print(f"  二级学科   {s['majors']} 个（需求要求 ≥ 50）")
    print(f"  技能标签   {s['skills']} 条（需求要求 ≥ 1000）")
    print()
    print("  各门类分布：")
    for l1, n in sorted(s["perL1"].items(), key=lambda kv: -kv[1]):
        majors = len(merged()[l1])
        print(f"    {l1:6}  {n:4} 条 / {majors} 个二级学科")

    missing = []
    if s["skills"] < 1000:
        missing.append(f"技能数差 {1000 - s['skills']} 条")
    if s["majors"] < 50:
        missing.append(f"二级学科差 {50 - s['majors']} 个")
    print()
    if missing:
        print("  ⚠ 距需求仍有差距：" + "；".join(missing))
    else:
        print("  ✓ 已满足需求规模要求")

    if args.out:
        Path(args.out).write_text(gen_sql(), encoding="utf-8")
        print(f"\n  已生成 SQL：{args.out}")
    if args.import_text:
        Path(args.import_text).write_text(gen_import_text(), encoding="utf-8")
        print(f"  已生成导入文本：{args.import_text}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
