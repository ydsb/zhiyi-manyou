def _norm_key(a: str, b: str) -> tuple[str, str]:
    """无向边的规范化键：保证 (A,B) 与 (B,A) 折叠成同一条。"""
    return (a, b) if a <= b else (b, a)


def load_skill_names(path: Path) -> tuple[set[str], dict[str, str]]:
    """
    读入在线技能清单。

    接受的每行格式（都是 mysql -N 的常见输出）：
        name
        category_l1|category_l2|name
    取最后一个字段作为技能名，因为名字本身可能含空格但不会含 '|'。

    返回 (技能名集合, 技能名 -> 一级门类)。

    用 utf-8-sig 读取：Windows 上用 PowerShell 重定向导出的文件常带 BOM，
    不当心会让第一个技能名多一个不可见字符，表现为"明明存在却校验失败"。
    """
    if not path.exists():
        raise SystemExit(
            f"[x] 技能清单不存在：{path}\n"
            f"    先导出（注意 --default-character-set，否则中文会乱码）：\n"
            f"    mysql --default-character-set=utf8mb4 -uroot -N -e \"SELECT "
            f"CONCAT(category_l1,'|',category_l2,'|',name) FROM zhiyi_manyou.zy_skill\" "
            f"> \"{path}\"")
    names: set[str] = set()
    categories: dict[str, str] = {}
    for raw in path.read_text(encoding="utf-8-sig").splitlines():
        line = raw.strip()
        if not line:
            continue
        parts = line.split("|")
        name = parts[-1].strip()
        names.add(name)
        if len(parts) >= 3:
            categories[name] = parts[0].strip()
    if not names:
        raise SystemExit(f"[x] 技能清单为空：{path}")
    return names, categories


def build_edges(skill_names: set[str]) -> tuple[list[dict], list[str]]:
    """
    把三份人工数据整理成待写入的边列表，同时收集**所有**问题而不是遇到第一个就退出
    —— 一次跑完看到全部错误，比改一个跑一次快得多。

    返回 (edges, problems)；problems 非空即视为失败。
    """
    problems: list[str] = []
    edges: list[dict] = []
    seen: dict[tuple[str, str, str], str] = {}

    def check(name: str, where: str) -> bool:
        if name not in skill_names:
            problems.append(f"{where}: 技能不存在于在线清单 -> 「{name}」")
            return False
        return True

    def add(src: str, dst: str, rel: str, weight: float, remark: str, where: str) -> None:
        if not check(src, where) or not check(dst, where):
            return
        if src == dst:
            problems.append(f"{where}: 自环边 -> 「{src}」")
            return
        if rel in (R_COMPLEMENT, R_SYNONYM):
            a, b = _norm_key(src, dst)
            key = (a, b, rel)
            if key in seen:
                problems.append(f"{where}: 与 {seen[key]} 重复 -> 「{a}」↔「{b}」({rel})")
                return
            seen[key] = where
            edges.append({"src": a, "dst": b, "rel": rel, "weight": weight,
                          "directed": 0, "remark": remark})
        else:
            key = (src, dst, rel)
            if key in seen:
                problems.append(f"{where}: 与 {seen[key]} 重复 -> 「{src}」→「{dst}」({rel})")
                return
            seen[key] = where
            edges.append({"src": src, "dst": dst, "rel": rel, "weight": weight,
                          "directed": 1, "remark": remark})

    for i, (a, b, w, why) in enumerate(COMPLEMENT, 1):
        add(a, b, R_COMPLEMENT, w, why, f"COMPLEMENT#{i}")
    for i, (a, b, w, why) in enumerate(PREREQUISITE, 1):
        add(a, b, R_PREREQUISITE, w, why, f"PREREQUISITE#{i}")
    for i, (a, b, why) in enumerate(SYNONYM, 1):
        add(a, b, R_SYNONYM, 1.0, why, f"SYNONYM#{i}")

    return edges, problems


def _sql_str(s: str) -> str:
    """包成 SQL 字符串字面量。数据里目前没有单引号，但转义不能省。"""
    return "'" + s.replace("\\", "\\\\").replace("'", "''") + "'"


def render_sql(edges: list[dict], categories: dict[str, str]) -> str:
    """
    产出幂等迁移 SQL。

    为什么用 INSERT ... SELECT 按 name 关联而不是写死 id：
      zy_skill.id 是自增的，本机与同学机器上同一技能的名字可能对应不同 id。
      写死 id 的迁移脚本换一台机器就会把边接错人 —— 而且不报错。
      按 name 关联虽然慢一点，但它只依赖"名字唯一"这个唯一键保证的事实。

    为什么 INSERT 之后还要跟一条 UPDATE：
      唯一键 uk_ontology_edge(src,dst,relation_type) 会让重复插入报 1062 并中断
      整个脚本，所以先用 NOT EXISTS 跳过已存在的边；但"只想调权重/改备注"
      的改动也需要生效，否则改了 remark 重跑一次毫无变化，人会以为脚本没执行。
    """
    n_comp = sum(1 for e in edges if e["rel"] == R_COMPLEMENT)
    n_pre = sum(1 for e in edges if e["rel"] == R_PREREQUISITE)
    n_syn = sum(1 for e in edges if e["rel"] == R_SYNONYM)

    L: list[str] = []
    L.append("-- =============================================================================")
    L.append("--  知驿·漫游 —— 技能知识图谱关系")
    L.append("--")
    L.append("--  本文件由 nlp-service/gen_graph.py 生成，请勿手工修改：")
    L.append("--  改内容请改生成器里的 COMPLEMENT / PREREQUISITE / SYNONYM 三张表，")
    L.append("--  再按生成器文件头的命令重新生成，否则下次生成会覆盖手工改动。")
    L.append("--")
    L.append("--  应用方式：")
    L.append("--      mysql --default-character-set=utf8mb4 -uroot -p zhiyi_manyou \\")
    L.append("--            < 10-ontology-graph.sql")
    L.append("--  幂等：可重复执行。已存在的边只刷新 weight/remark，不会重复插入。")
    L.append("--")
    L.append("--  relation_type 语义：")
    L.append("--    COMPLEMENT   互补协作，无向（directed=0）—— 隐性需求挖掘只采信这类边")
    L.append("--    PREREQUISITE 先决条件，有向（directed=1，src 先于 dst）—— 用于学习路径")
    L.append("--    SYNONYM      同义映射，无向 —— 用于消解跨域术语差异")
    L.append("-- =============================================================================")
    L.append("")
    L.append("USE `zhiyi_manyou`;")
    L.append("")
    L.append(f"-- 本批 {len(edges)} 条边：COMPLEMENT {n_comp} / PREREQUISITE {n_pre} / SYNONYM {n_syn}")
    L.append("")

    current_rel = None
    for idx, e in enumerate(edges, 1):
        if e["rel"] != current_rel:
            current_rel = e["rel"]
            L.append("")
            L.append("-- " + "-" * 74)
            L.append(f"-- {current_rel}")
            L.append("-- " + "-" * 74)
        src_cat = categories.get(e["src"], "?")
        dst_cat = categories.get(e["dst"], "?")
        arrow = "→" if e["rel"] == R_PREREQUISITE else "↔"
        cross = "  [跨门类]" if src_cat != dst_cat else ""
        L.append("")
        L.append(f"-- {idx}. {e['src']} ({src_cat}) {arrow} {e['dst']} ({dst_cat}){cross}")
        L.append(f"--    {e['remark']}")
        L.append("INSERT INTO `zy_skill_ontology`")
        L.append("    (`src_skill_id`, `dst_skill_id`, `relation_type`, `weight`, `directed`, `remark`)")
        L.append("SELECT s1.id, s2.id, "
                 f"'{e['rel']}', {e['weight']:.4f}, {e['directed']}, {_sql_str(e['remark'])}")
        L.append("FROM `zy_skill` s1, `zy_skill` s2")
        L.append(f"WHERE s1.`name` = {_sql_str(e['src'])}")
        L.append(f"  AND s2.`name` = {_sql_str(e['dst'])}")
        L.append("  AND NOT EXISTS (SELECT 1 FROM `zy_skill_ontology` o")
        L.append("                  WHERE o.`src_skill_id` = s1.id")
        L.append("                    AND o.`dst_skill_id` = s2.id")
        L.append(f"                    AND o.`relation_type` = '{e['rel']}');")
        L.append("UPDATE `zy_skill_ontology` o")
        L.append(f"JOIN `zy_skill` s1 ON s1.`name` = {_sql_str(e['src'])}")
        L.append(f"JOIN `zy_skill` s2 ON s2.`name` = {_sql_str(e['dst'])}")
        L.append(f"SET o.`weight` = {e['weight']:.4f}, o.`directed` = {e['directed']},")
        L.append(f"    o.`remark` = {_sql_str(e['remark'])}")
        L.append("WHERE o.`src_skill_id` = s1.id AND o.`dst_skill_id` = s2.id")
        L.append(f"  AND o.`relation_type` = '{e['rel']}';")

    L.append("")
    L.append("-- =============================================================================")
    L.append("-- 统计核对")
    L.append("-- =============================================================================")
    L.append("SELECT `relation_type`, COUNT(*) AS edges,")
    L.append("       SUM(CASE WHEN `directed` = 1 THEN 1 ELSE 0 END) AS directed_edges")
    L.append("FROM `zy_skill_ontology` GROUP BY `relation_type` ORDER BY edges DESC;")
    L.append("")
    L.append("-- 跨门类边占比（体现\"跨学科\"是否真的落到数据上）")
    L.append("SELECT SUM(CASE WHEN a.category_l1 <> b.category_l1 THEN 1 ELSE 0 END) AS cross_category,")
    L.append("       COUNT(*) AS total,")
    L.append("       ROUND(100.0 * SUM(CASE WHEN a.category_l1 <> b.category_l1 THEN 1 ELSE 0 END)")
    L.append("             / COUNT(*), 1) AS cross_pct")
    L.append("FROM `zy_skill_ontology` o")
    L.append("JOIN `zy_skill` a ON a.id = o.src_skill_id")
    L.append("JOIN `zy_skill` b ON b.id = o.dst_skill_id;")
    L.append("")
    L.append("-- 孤点技能数：完全没有任何边的技能，就是图谱里看不见的节点")
    L.append("SELECT COUNT(*) AS isolated_skills FROM `zy_skill` s")
    L.append("WHERE s.`status` = 1")
    L.append("  AND NOT EXISTS (SELECT 1 FROM `zy_skill_ontology` o")
    L.append("                  WHERE o.src_skill_id = s.id OR o.dst_skill_id = s.id);")
    L.append("")
    return "\n".join(L)


def cmd_stats(edges: list[dict], skill_names: set[str], categories: dict[str, str]) -> None:
    by_rel = Counter(e["rel"] for e in edges)
    cross = sum(1 for e in edges if categories.get(e["src"]) != categories.get(e["dst"]))
    touched = {e["src"] for e in edges} | {e["dst"] for e in edges}

    print("=" * 68)
    print("  技能知识图谱关系统计")
    print("=" * 68)
    print(f"  在线技能总数     : {len(skill_names)}")
    print(f"  本批边数         : {len(edges)}")
    for rel, cnt in by_rel.most_common():
        per = len({e["src"] for e in edges if e["rel"] == rel} |
                  {e["dst"] for e in edges if e["rel"] == rel})
        print(f"    {rel:<14}: {cnt:>4}   （涉及 {per} 个技能）")
    print(f"  跨门类边         : {cross}  ({100.0 * cross / max(len(edges), 1):.1f}%)")
    print(f"  被连接到的技能   : {len(touched)} / {len(skill_names)} "
          f"({100.0 * len(touched) / max(len(skill_names), 1):.1f}%)")
    print(f"  仍是孤点的技能   : {len(skill_names) - len(touched)}")

    cat_touched = Counter(categories.get(n, "?") for n in touched)
    cat_total = Counter(categories.get(n, "?") for n in skill_names)
    print("\n  各门类被连接的技能数：")
    for cat, total in cat_total.most_common():
        got = cat_touched.get(cat, 0)
        bar = "#" * int(20.0 * got / max(total, 1))
        print(f"    {cat:<6} {got:>4} / {total:<4} {bar}")

    degree: Counter = Counter()
    for e in edges:
        degree[e["src"]] += 1
        degree[e["dst"]] += 1
    print("\n  度数最高的技能（图谱里的枢纽节点）：")
    for name, deg in degree.most_common(12):
        print(f"    {deg:>3}  {name}")
    print("=" * 68)


def main() -> int:
    ap = argparse.ArgumentParser(
        description="生成/校验技能知识图谱关系 SQL",
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--skills", required=True, type=Path,
                    help="在线技能清单（每行 name 或 l1|l2|name），必填")
    ap.add_argument("--out", type=Path, help="输出的 SQL 文件路径")
    ap.add_argument("--stats", action="store_true", help="只打印统计")
    ap.add_argument("--check", action="store_true", help="只校验技能名，不写文件")
    args = ap.parse_args()

    skill_names, categories = load_skill_names(args.skills)
    edges, problems = build_edges(skill_names)

    print(f"[*] 在线技能 {len(skill_names)} 个，待写入边 {len(edges)} 条")
    if problems:
        print(f"\n[x] 发现 {len(problems)} 个问题，未生成任何文件：")
        for p in problems:
            print(f"    - {p}")
        print("\n    这些边被拒绝是**有意为之**：zy_skill_ontology 没有外键约束，"
              "\n    指向不存在技能的边会被数据库安静收下，然后永远查不出来，"
              "\n    表现为图谱补全里某些技能怎么都不触发关联。")
        return 1
    print("[+] 技能名全部校验通过，无重复边、无自环")

    if args.stats:
        cmd_stats(edges, skill_names, categories)
        return 0
    if args.check:
        print("[+] --check 模式，未写文件")
        return 0

    sql = render_sql(edges, categories)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(sql, encoding="utf-8")
        print(f"[+] 已写出 {args.out}（{len(sql.encode('utf-8'))} 字节）")
    else:
        try:
            sys.stdout.reconfigure(encoding="utf-8")
        except Exception:
            pass
        print(sql)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
