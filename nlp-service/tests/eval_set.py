"""
语义匹配评测集与指标（S3 · AC-03）

【为什么需要专门的评测集，而不是跑几个样例看看】
  验收标准 AC-03 要求"匹配准确率 ≥ 70%"，这个数字必须**可复现、可复核**。
  开发中我用几个样例粗看效果时，实际上犯了两个方法错误：

    1. **只认一个正确答案**：查询「帮我剪个宣传视频加特效」，
       返回「短视频创作与运营」「影视特效与合成」都算相关，
       只认「视频剪辑」会低估系统；
    2. **只看 Top-1**：检索场景下用户会看前几条，
       正确结果排在第 2 位同样有价值，只统计 Top-1 会低估。

  因此本评测集为每条查询标注**一组可接受的技能**，并同时报告：
    - Hit@1 / Hit@3 / Hit@5：正确结果是否出现在前 K 位
    - MRR（平均倒数排名）：正确结果的排名倒数均值，对排名敏感
    - 准确率（本项目的 AC-03 口径）：Hit@3，即"前 3 条内命中即算对"

【标注原则】
  可接受集合按"用户拿这条结果会不会满意"判断，而不是按"是否唯一正确"。
  例如查询"想找人教我做动画"，可接受「JS 动画与交互实现」与「三维动画与建模」——
  前者更贴切、后者也能接受，都算命中。

作者：李泽宬
"""

