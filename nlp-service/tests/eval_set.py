def load_cases() -> list[tuple[str, set[str], str]]:
    return CASES


def summarize(results: list[dict]) -> dict:
    """汇总评测指标。

    @param results 每项含 hit1/hit3/hit5/reciprocal_rank/top1
    @return 指标字典
    """
    n = len(results)
    if n == 0:
        return {}
    hit1 = sum(1 for r in results if r["hit1"])
    hit3 = sum(1 for r in results if r["hit3"])
    hit5 = sum(1 for r in results if r["hit5"])
    mrr = sum(r["reciprocal_rank"] for r in results) / n
    return {
        "count": n,
        "hit1": hit1,
        "hit3": hit3,
        "hit5": hit5,
        "accuracy_hit1": round(hit1 / n, 4),
        "accuracy_hit3": round(hit3 / n, 4),
        "accuracy_hit5": round(hit5 / n, 4),
        "mrr": round(mrr, 4),
    }


